@app.post(
    "/route-intent",
    response_model=RoutingResult,
)
@app.post(
    "/encode-intent",
    response_model=RoutingResult,
)
def route_intent(
    request: EncodeRequest,
) -> RoutingResult:
    # -----------------------------------------------------
    # Step 1: Interpret and normalize the intention
    # -----------------------------------------------------

    try:
        intent = interpret_intention(
            request.message
        )

        intent = normalize_requested_output(
            original_message=request.message,
            intent=intent,
        )

    except Exception as error:
        raise HTTPException(
            status_code=502,
            detail=(
                f"Could not interpret intention: "
                f"{error}"
            ),
        ) from error

    # -----------------------------------------------------
    # Validate the interpreted intention
    # -----------------------------------------------------

    if intent.action == "unsupported":
        raise HTTPException(
            status_code=422,
            detail={
                "error": "unsupported_action",
                "message": (
                    "The request contains an unsupported "
                    "action or more than one action."
                ),
            },
        )

    if (
        intent.needs_clarification
        or intent.target.type != "order"
        or not intent.target.id
    ):
        raise HTTPException(
            status_code=422,
            detail={
                "error": "clarification_required",
                "question": (
                    intent.clarification_question
                    or "Which order should be used?"
                ),
            },
        )

    # -----------------------------------------------------
    # Step 2: Select the receiving Space
    # -----------------------------------------------------

    try:
        selected_route = switch_intention(
            intent
        )

    except LookupError as error:
        raise HTTPException(
            status_code=404,
            detail={
                "error": "route_not_found",
                "message": str(error),
            },
        ) from error

    # -----------------------------------------------------
    # Construct the trusted protocol message
    # -----------------------------------------------------

    try:
        protocol_message = build_protocol_message(
            intent=intent,
            route=selected_route,
        )

    except ValueError as error:
        raise HTTPException(
            status_code=422,
            detail={
                "error": "invalid_protocol_message",
                "message": str(error),
            },
        ) from error

    return RoutingResult(
        parsed_intent=intent,
        selected_route=selected_route,
        protocol_message=protocol_message,
    )